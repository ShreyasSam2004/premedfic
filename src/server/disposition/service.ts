/**
 * Official determinations and source-of-record synchronization.
 *
 * Four states are kept distinct:
 *   READY_FOR_AUTHORIZED_DISPOSITION  — review complete, nothing approved yet
 *   (determination recorded)          — an authorized official signed a decision
 *   DISPOSITION_PENDING_CONFIRMATION  — submitted to the municipal system of record
 *   OFFICIALLY_CLOSED                 — the system of record confirmed the update
 */
import { and, desc, eq } from "drizzle-orm";
import { DETERMINATION_META, DETERMINATION_TYPES, type DeterminationType } from "@/domain/workflow";
import { db, transaction } from "../db/client";
import { dispositionSubmissions, permits, reviewDecisions, triageResults, type Permit, type SignatureMeta } from "../db/schema";
import { requirePermission, systemContext, type ActorContext } from "../auth/context";
import { recordAudit } from "../audit/audit";
import { ConflictError, NotFoundError, ValidationError } from "../errors";
import { isoDate, now, randomToken, sha256 } from "../util";
import { loadCaseForOrg, transitionCase } from "../workflow/service";

export const ATTESTATION_TEXT =
  "I am an official authorized to make this determination. I made it based on my review of the case record. It is not generated by software.";

export interface PermitLookup {
  finaled: boolean;
  status: string;
  finalInspectionAt: string | null;
  reference: string;
  note: string;
  simulated: boolean;
}

/** Adapter to the municipality's permit system of record (Accela, Tyler EnerGov, etc.). */
export interface SourceOfRecordAdapter {
  readonly id: string;
  readonly live: boolean;
  submitDisposition(payload: Record<string, unknown>): Promise<{ accepted: boolean; submissionRef: string }>;
  /** What the system of record shows for a permit: its status and any passed final inspection. */
  lookupPermit(permit: Pick<Permit, "permitNumber" | "issuedAt" | "finalInspectionAt">): Promise<PermitLookup>;
}

export const simulatedPermitSystem: SourceOfRecordAdapter = {
  id: "simulated_permit_system",
  live: false,
  async submitDisposition() {
    return { accepted: true, submissionRef: `SIM-SUB-${randomToken(6).toUpperCase()}` };
  },
  // Stand-in for a live lookup. Deterministic: it shows a final only where the
  // imported final inspection date is internally consistent, so both outcomes
  // can be demonstrated. A real adapter answers from the permit system itself.
  async lookupPermit(p) {
    const reference = `SIM-PMT-${sha256(p.permitNumber).slice(0, 8).toUpperCase()}`;
    const f = p.finalInspectionAt;
    const consistent = Boolean(f && (!p.issuedAt || f >= p.issuedAt) && f <= isoDate(now()));
    return consistent
      ? { finaled: true, status: "Final", finalInspectionAt: f, reference, note: "Simulated permit system shows the permit finaled with a passed final inspection.", simulated: true }
      : { finaled: false, status: "Expired", finalInspectionAt: null, reference, note: "Simulated permit system shows no passed final inspection on file.", simulated: true };
  },
};

export async function recordDetermination(
  ctx: ActorContext,
  caseId: string,
  input: { determination: string; reason: string; attested: boolean; expectedVersion?: number | null; idempotencyKey?: string | null },
) {
  const user = requirePermission(ctx, "disposition:record");
  if (!DETERMINATION_TYPES.includes(input.determination as DeterminationType)) throw new ValidationError("Unknown determination type");
  const determination = input.determination as DeterminationType;
  if (!input.attested) throw new ValidationError("The attestation must be confirmed to record an official determination");
  if (input.reason.trim().length < 20) throw new ValidationError("State the basis for the determination (at least 20 characters)");

  return transaction(async () => {
    const c = await loadCaseForOrg(ctx.orgId, caseId);
    const result = await transitionCase(ctx, {
      caseId,
      transition: "record_determination",
      reason: input.reason,
      proposedDetermination: determination,
      expectedVersion: input.expectedVersion,
      idempotencyKey: input.idempotencyKey,
      metadata: { determination },
    });
    if (result.alreadyApplied) return result;
    const [tr] = c.currentTriageId ? await db().select().from(triageResults).where(eq(triageResults.id, c.currentTriageId)) : [];
    const [permit] = await db().select().from(permits).where(eq(permits.id, c.permitId));
    const signedAt = now();
    const signature: SignatureMeta = {
      name: user.name,
      title: user.title,
      role: user.role,
      userId: user.userId,
      signedAt: signedAt.toISOString(),
      method: "authenticated_session_attestation",
      attestation: ATTESTATION_TEXT,
    };
    const [d] = await db()
      .insert(reviewDecisions)
      .values({
        orgId: ctx.orgId,
        caseId,
        decisionType: "official_determination",
        determination,
        summary: DETERMINATION_META[determination].label,
        reason: input.reason.trim(),
        actorUserId: user.userId,
        actorRole: user.role,
        actorName: user.name,
        signature,
        ruleSetId: tr?.ruleSetId ?? null,
        ruleSetVersion: tr?.ruleSetVersion ?? null,
        createdAt: signedAt,
      })
      .returning();
    const payload = {
      permitNumber: permit.permitNumber,
      sourceSystem: permit.sourceSystem,
      sourceRecordId: permit.sourceRecordId,
      determination,
      closes: DETERMINATION_META[determination].closes,
      decidedBy: user.name,
      decidedAt: signedAt.toISOString(),
      decisionId: d.id,
    };
    const sub = await simulatedPermitSystem.submitDisposition(payload);
    const [submission] = await db()
      .insert(dispositionSubmissions)
      .values({
        orgId: ctx.orgId,
        caseId,
        decisionId: d.id,
        adapter: simulatedPermitSystem.id,
        payload: { ...payload, submissionRef: sub.submissionRef },
        status: "submitted",
        submittedAt: now(),
      })
      .returning();
    await recordAudit(ctx, {
      action: "disposition.determination_recorded",
      entityType: "review_decision",
      entityId: d.id,
      caseId,
      summary: `Official determination recorded by ${user.name}: ${DETERMINATION_META[determination].label}. Submitted to system of record (${simulatedPermitSystem.id}); not yet confirmed.`,
      metadata: { determination, submissionId: submission.id, adapterLive: simulatedPermitSystem.live },
    });
    return { ...result, decision: d, submission };
  });
}

async function pendingSubmission(orgId: string, submissionId: string) {
  const [s] = await db()
    .select()
    .from(dispositionSubmissions)
    .where(and(eq(dispositionSubmissions.id, submissionId), eq(dispositionSubmissions.orgId, orgId)));
  if (!s) throw new NotFoundError("Submission");
  if (s.status !== "submitted") throw new ConflictError("This submission has already been resolved");
  const [d] = await db().select().from(reviewDecisions).where(eq(reviewDecisions.id, s.decisionId));
  return { s, determination: d.determination as DeterminationType };
}

/**
 * Simulates the permit system of record responding to a submission. In
 * production this is replaced by the adapter's webhook or polling handler,
 * which calls `applySourceResponse` with the system actor.
 */
export async function simulateSourceResponse(ctx: ActorContext, submissionId: string, outcome: "confirmed" | "rejected") {
  requirePermission(ctx, "disposition:confirm");
  return applySourceResponse(ctx.orgId, submissionId, {
    outcome,
    externalReference: outcome === "confirmed" ? `SIM-PMT-${randomToken(5).toUpperCase()}` : null,
    note: outcome === "confirmed" ? "Simulated permit system accepted the update" : "Simulated permit system rejected the update",
  });
}

export async function applySourceResponse(orgId: string, submissionId: string, input: { outcome: "confirmed" | "rejected"; externalReference: string | null; note: string }) {
  const sys = systemContext(orgId, `source-of-record:${simulatedPermitSystem.id}`);
  return transaction(async () => {
    const { s, determination } = await pendingSubmission(orgId, submissionId);
    const transition =
      input.outcome === "rejected" ? "source_rejected" : DETERMINATION_META[determination].closes ? "confirm_source_closure" : "confirm_source_other_outcome";
    // Transition first: its guard requires the submission to still be pending.
    const result = await transitionCase(sys, {
      caseId: s.caseId,
      transition,
      reason: `${input.note}${input.externalReference ? ` (reference ${input.externalReference})` : ""}`,
      idempotencyKey: `source:${s.id}`,
      metadata: { submissionId: s.id, externalReference: input.externalReference },
    });
    await db()
      .update(dispositionSubmissions)
      .set({ status: input.outcome, externalReference: input.externalReference, respondedAt: now(), confirmedByType: "system", confirmedBy: sys.actor.type === "system" ? sys.actor.name : null, responseNote: input.note })
      .where(eq(dispositionSubmissions.id, s.id));
    return result;
  });
}

/** Documented, authorized manual confirmation, for systems without an integration. */
export async function recordManualConfirmation(ctx: ActorContext, submissionId: string, input: { externalReference: string; note: string }) {
  const user = requirePermission(ctx, "disposition:confirm");
  if (input.externalReference.trim().length < 3) throw new ValidationError("Enter the reference number shown in the system of record");
  if (input.note.trim().length < 10) throw new ValidationError("Describe how the update was confirmed (at least 10 characters)");
  return transaction(async () => {
    const { s, determination } = await pendingSubmission(ctx.orgId, submissionId);
    const result = await transitionCase(ctx, {
      caseId: s.caseId,
      transition: DETERMINATION_META[determination].closes ? "confirm_source_closure" : "confirm_source_other_outcome",
      reason: `Manual confirmation by ${user.name}: ${input.note.trim()} (reference ${input.externalReference.trim()})`,
      idempotencyKey: `manual-confirm:${s.id}`,
      metadata: { submissionId: s.id, externalReference: input.externalReference.trim(), manual: true },
    });
    await db()
      .update(dispositionSubmissions)
      .set({ status: "confirmed", externalReference: input.externalReference.trim(), respondedAt: now(), confirmedByType: "user", confirmedBy: user.userId, responseNote: input.note.trim() })
      .where(eq(dispositionSubmissions.id, s.id));
    return result;
  });
}

export async function reopenCase(ctx: ActorContext, caseId: string, reason: string) {
  requirePermission(ctx, "cases:reopen");
  return transitionCase(ctx, { caseId, transition: "reopen_case", reason });
}

export async function latestSubmission(orgId: string, caseId: string) {
  const [s] = await db()
    .select()
    .from(dispositionSubmissions)
    .where(and(eq(dispositionSubmissions.orgId, orgId), eq(dispositionSubmissions.caseId, caseId)))
    .orderBy(desc(dispositionSubmissions.submittedAt))
    .limit(1);
  return s ?? null;
}
